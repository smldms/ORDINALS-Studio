"""Compile locally bundled Google Fonts into deterministic plotter contours.
Requires fontTools. Original TTFs and OFL notices are retained in dist/fonts.
"""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
import urllib.request,json,hashlib,math
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.basePen import BasePen
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'dist/fonts';OUT.mkdir(exist_ok=True)
SPECS=[('archivo','Archivo Black','archivoblack','ArchivoBlack-Regular.ttf',{}),('bebas','Bebas Neue','bebasneue','BebasNeue-Regular.ttf',{}),('roboto','Roboto','roboto','Roboto[wdth,wght].ttf',{'wght':400,'wdth':100}),('grotesk','Space Grotesk','spacegrotesk','SpaceGrotesk[wght].ttf',{'wght':500})]
CHARS=''.join(chr(c) for c in range(32,256))+''.join(chr(c) for c in range(0x100,0x180))+'ŒœŸẞ–—‘’“”…€•→←↑↓'
class FlattenPen(BasePen):
 def __init__(self,gs,cap):super().__init__(gs);self.cap=cap;self.contours=[];self.points=[];self.pos=(0,0);self.tol=cap*.001
 def _moveTo(self,p):self.finish(False);self.points=[p];self.pos=p
 def _lineTo(self,p):self.points.append(p);self.pos=p
 def _closePath(self):self.finish(True)
 def _endPath(self):self.finish(False)
 def finish(self,close):
  if len(self.points)>1:
   if close and self.points[-1]!=self.points[0]:self.points.append(self.points[0])
   self.contours.append([[round(x/self.cap,4),round(1-y/self.cap,4)] for x,y in self.points])
  self.points=[]
 def _qCurveToOne(self,c,b):
  def rec(a,c,b,depth=0):
   if depth>12 or math.hypot(a[0]-2*c[0]+b[0],a[1]-2*c[1]+b[1])<=4*self.tol:self.points.append(b);return
   ac=((a[0]+c[0])/2,(a[1]+c[1])/2);cb=((c[0]+b[0])/2,(c[1]+b[1])/2);mid=((ac[0]+cb[0])/2,(ac[1]+cb[1])/2)
   rec(a,ac,mid,depth+1);rec(mid,cb,b,depth+1)
  rec(self.pos,c,b);self.pos=b
 def _curveToOne(self,c,d,b):
  def rec(a,c,d,b,depth=0):
   err=max(math.hypot(a[0]-2*c[0]+d[0],a[1]-2*c[1]+d[1]),math.hypot(c[0]-2*d[0]+b[0],c[1]-2*d[1]+b[1]))
   if depth>12 or err<=3*self.tol:self.points.append(b);return
   mid=lambda u,v:((u[0]+v[0])/2,(u[1]+v[1])/2)
   ac=mid(a,c);cd=mid(c,d);db=mid(d,b);acd=mid(ac,cd);cdb=mid(cd,db);z=mid(acd,cdb)
   rec(a,ac,acd,z,depth+1);rec(z,cdb,db,b,depth+1)
  rec(self.pos,c,d,b);self.pos=b

def fetch(spec):
 key,name,folder,file,axes=spec
 for remote,local in [(file,key+'.ttf'),('OFL.txt',key+'-OFL.txt')]:
  dest=OUT/local
  if not dest.exists():
   u='https://raw.githubusercontent.com/google/fonts/main/ofl/'+folder+'/'+urllib.parse.quote(remote)
   dest.write_bytes(urllib.request.urlopen(u,timeout=45).read())
 return spec

def compile_font(spec):
 key,name,folder,file,axes=spec
 f=TTFont(OUT/(key+'.ttf'))
 if 'fvar' in f:f=instantiateVariableFont(f,axes,inplace=False)
 cap=getattr(f['OS/2'],'sCapHeight',0) or f['head'].unitsPerEm*.7
 gs=f.getGlyphSet();cmap=f.getBestCmap();glyphs={};names={}
 for ch in CHARS:
  gn=cmap.get(ord(ch))
  if not gn:continue
  pen=FlattenPen(gs,cap);gs[gn].draw(pen);pen.finish(False)
  glyphs[ch]={'a':round(f['hmtx'][gn][0]/cap,4),'p':pen.contours};names[ch]=gn
 # Export GPOS kern pair adjustments, including class-based lookups.
 subs=[]
 if 'GPOS' in f:
  table=f['GPOS'].table
  ids={i for fr in table.FeatureList.FeatureRecord if fr.FeatureTag=='kern' for i in fr.Feature.LookupListIndex}
  for i in sorted(ids):
   lookup=table.LookupList.Lookup[i]
   for st in lookup.SubTable:
    if lookup.LookupType==9:st=st.ExtSubTable
    if hasattr(st,'PairSet') or hasattr(st,'Class1Record'):subs.append(st)
 kern={}
 for left,gn in names.items():
  for right,gn2 in names.items():
   value=0
   for st in subs:
    if gn not in st.Coverage.glyphs:continue
    if st.Format==1:
     for pair in st.PairSet[st.Coverage.glyphs.index(gn)].PairValueRecord:
      if pair.SecondGlyph==gn2:value+=getattr(pair.Value1,'XAdvance',0) or 0;break
    elif st.Format==2:
     a=st.ClassDef1.classDefs.get(gn,0);b=st.ClassDef2.classDefs.get(gn2,0)
     value+=getattr(st.Class1Record[a].Class2Record[b].Value1,'XAdvance',0) or 0
   if value:kern[left+right]=round(value/cap,4)
 print(key,len(glyphs),'glyphs,',len(kern),'kern pairs',flush=True)
 return key,{'name':name,'glyphs':glyphs,'kern':kern,'source':'https://github.com/google/fonts/tree/main/ofl/'+folder,'sha256':hashlib.sha256((OUT/(key+'.ttf')).read_bytes()).hexdigest()}
with ThreadPoolExecutor(max_workers=4) as pool:specs=list(pool.map(fetch,SPECS))
data=dict(compile_font(spec) for spec in specs)
(ROOT/'dist/font-data.js').write_text('/* Google Fonts outlines; original licenses: fonts/*-OFL.txt. Generated by scripts/build-font-outlines.py. */\nconst VECTOR_FONTS='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n')
print('Bundled outline data:',(ROOT/'dist/font-data.js').stat().st_size,'bytes')
